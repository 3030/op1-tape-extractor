#!/usr/bin/env bash
set -euo pipefail

# Build universal binary for Mac App Store by building both architectures
# and merging them with lipo

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_NAME="OP-1 Loop Extractor.app"
APP_PATH="${ROOT_DIR}/dist/${APP_NAME}"
PKG_PATH="${ROOT_DIR}/dist/OP1LoopExtractor-AppStore.pkg"
ENTITLEMENTS="${ROOT_DIR}/entitlements-appstore.plist"
PROFILE="${ROOT_DIR}/OP1LE_For_GitHub.provisionprofile"
BUILD_NUMBER_FILE="${ROOT_DIR}/.build_number"

DISTRIBUTION_ID="Apple Distribution: Nathan Schmold (UZFS64KXD5)"
INSTALLER_ID="3rd Party Mac Developer Installer: Nathan Schmold (UZFS64KXD5)"

# Auto-increment build number starting from 50
if [[ -f "${BUILD_NUMBER_FILE}" ]]; then
  BUILD_NUMBER=$(cat "${BUILD_NUMBER_FILE}")
  BUILD_NUMBER=$((BUILD_NUMBER + 1))
else
  BUILD_NUMBER=50
fi
echo "${BUILD_NUMBER}" > "${BUILD_NUMBER_FILE}"

VERSION="1.0.${BUILD_NUMBER}"
echo "==> Build version: ${VERSION}"

# Update version.py with new build number
cat > "${ROOT_DIR}/version.py" <<EOF
# Auto-generated version file
# This file is generated by build script
# Format: MAJOR.MINOR.BUILD_NUMBER

__version__ = "${VERSION}"
EOF

if [[ ! -f "${ENTITLEMENTS}" ]]; then
  echo "Missing entitlements file at ${ENTITLEMENTS}" >&2
  exit 1
fi

if [[ ! -f "${PROFILE}" ]]; then
  echo "Missing provisioning profile at ${PROFILE}" >&2
  exit 1
fi

echo "==> Building universal binary (arm64 + x86_64)"
rm -rf "${ROOT_DIR}/dist/OP-1 Loop Extractor" "${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app" "${ROOT_DIR}/dist/OP-1 Loop Extractor-x86_64.app" "${APP_PATH}" "${PKG_PATH}"

# Check if we need both Homebrew installations
ARM_BREW="/opt/homebrew"
X86_BREW="/usr/local"

# Build ARM64 version
echo "==> Building arm64 version..."
source "${ROOT_DIR}/.venv/bin/activate"
PYINSTALLER_CONFIG_DIR="${ROOT_DIR}/.pyinstaller/arm64" \
PYINSTALLER_CACHE_DIR="${ROOT_DIR}/.pyinstaller/arm64" \
arch -arm64 pyinstaller mac-appstore-arm64.spec --noconfirm
mv "${APP_PATH}" "${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app"
deactivate

# Build x86_64 version
echo "==> Building x86_64 version..."
if [[ ! -d "${X86_BREW}/bin" ]]; then
  echo "ERROR: x86_64 Homebrew not found at ${X86_BREW}"
  echo "Please install Rosetta Homebrew first:"
  echo "  arch -x86_64 /bin/bash -c \"\$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)\""
  exit 1
fi

# Use x86_64 Python from Rosetta Homebrew
if [[ -d "${ROOT_DIR}/.venv-x86" ]]; then
  source "${ROOT_DIR}/.venv-x86/bin/activate"
else
  echo "Creating x86_64 venv..."
  arch -x86_64 ${X86_BREW}/bin/python3 -m venv "${ROOT_DIR}/.venv-x86"
  source "${ROOT_DIR}/.venv-x86/bin/activate"
  pip install -r "${ROOT_DIR}/requirements.txt"
fi

PYINSTALLER_CONFIG_DIR="${ROOT_DIR}/.pyinstaller/x86" \
PYINSTALLER_CACHE_DIR="${ROOT_DIR}/.pyinstaller/x86" \
arch -x86_64 pyinstaller mac-appstore-x86.spec --noconfirm
mv "${APP_PATH}" "${ROOT_DIR}/dist/OP-1 Loop Extractor-x86_64.app"
deactivate

# Merge into universal binary
echo "==> Creating universal binary..."
cp -R "${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app" "${APP_PATH}"

# Find all Mach-O binaries and merge them
find "${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app" -type f | while read arm64_file; do
  # Check if it's a Mach-O binary
  if file "$arm64_file" | grep -q "Mach-O"; then
    rel_path="${arm64_file#${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app/}"
    x86_file="${ROOT_DIR}/dist/OP-1 Loop Extractor-x86_64.app/${rel_path}"
    universal_file="${APP_PATH}/${rel_path}"

    if [[ -f "$x86_file" ]] && file "$x86_file" | grep -q "Mach-O"; then
      echo "Merging: ${rel_path}"
      lipo -create "$arm64_file" "$x86_file" -output "$universal_file" || {
        echo "Warning: Could not merge $rel_path, using arm64 version"
        cp "$arm64_file" "$universal_file"
      }
    fi
  fi
done

# Clean up architecture-specific builds
rm -rf "${ROOT_DIR}/dist/OP-1 Loop Extractor-arm64.app" "${ROOT_DIR}/dist/OP-1 Loop Extractor-x86_64.app"

if [[ ! -d "${APP_PATH}" ]]; then
  echo "Expected app bundle not found at ${APP_PATH}" >&2
  exit 1
fi

echo "==> Removing quarantine attributes from app bundle"
xattr -cr "${APP_PATH}"

echo "==> Embedding provisioning profile"
cp "${PROFILE}" "${APP_PATH}/Contents/embedded.provisionprofile"
xattr -d com.apple.quarantine "${APP_PATH}/Contents/embedded.provisionprofile" 2>/dev/null || true

echo "==> Signing app bundle (deep)"
codesign --force --deep --options runtime \
  --entitlements "${ENTITLEMENTS}" \
  --sign "${DISTRIBUTION_ID}" "${APP_PATH}"

echo "==> Verifying signature"
codesign --verify --deep --strict --verbose=2 "${APP_PATH}"

echo "==> Verifying architectures"
file "${APP_PATH}/Contents/MacOS/OP-1 Loop Extractor"
lipo -info "${APP_PATH}/Contents/MacOS/OP-1 Loop Extractor"

echo "==> Building signed pkg for MAS"
productbuild --component "${APP_PATH}" /Applications \
  --sign "${INSTALLER_ID}" \
  "${PKG_PATH}"

echo "==> Done."
echo "App bundle: ${APP_PATH}"
echo "MAS pkg:    ${PKG_PATH}"
